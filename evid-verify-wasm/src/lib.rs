//! EVID mobile verifier wasm binding (verdict logic single-sourced from `evid-verify-core`)
//!
//! Both routes share the [`handlers`] verdict layer:
//!
//! - **route A (primary artifact)**: the [`abi`] extern "C" byte ABI — input
//!   JSON bytes (JS writes into linear memory via [`abi::wasm_alloc`]), output
//!   `[u32 LE length][JSON]` package. Zero imports, zero JS glue, works with a
//!   plain `WebAssembly.instantiate`; the single-file HTML verifier
//!   (`dist/index.html`, generated by `build-dist.ps1`) uses this route.
//! - **route B**: [`bindings`] enabled via `--features bindgen`
//!   (`#[wasm_bindgen]` string interface), for the wasm-pack / npm ecosystem.
//!
//! # Verdict-surface contract (three isomorphic entries)
//!
//! Input JSON → verdict JSON (never panics; a parse failure is also a
//! fail-closed red):
//!
//! - Export surface: export doc (bare shape or `{"export": …}` wrapper, v1.0
//!   only) → `{ok, verdicts, stopped_at, tail_hash, last_hash_matches}`
//! - WAL surface: WAL line series (`{"lines":[…]}` or bare array) →
//!   `{ok, verdicts, stopped_at, tail_hash}`
//! - Anchor surface: `{"seals":[…], "keys":{key_id: public key hex}}` →
//!   `{ok, seal_count}` or `{ok:false, error}`
//!
//! # Honest boundary
//!
//! The verifier judges "the chain was not tampered with", not "the chain head
//! records the truth" — authenticity is carried by signed anchors and the
//! threshold-signature system; the public-key trust root is established by the
//! user (pasted manually into the HTML UI table, zero hardcoding).

