# Build single-file HTML verifier: wasm release build -> base64 -> inject into template -> dist/index.html
# Usage: powershell -ExecutionPolicy Bypass -File build-dist.ps1   (run in this crate dir)
# NOTE: keep this script ASCII-only (Windows PowerShell reads BOM-less .ps1 as ANSI/GBK;
#       UTF-8 Chinese comments may swallow newlines and break statements).
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

cargo build -p evid-verify-wasm --target wasm32-unknown-unknown --release
if ($LASTEXITCODE -ne 0) { throw "wasm build failed" }

$wasmPath = Join-Path $PSScriptRoot "..\target\wasm32-unknown-unknown\release\evid_verify_wasm.wasm"
if (-not (Test-Path $wasmPath)) { throw "wasm artifact not found: $wasmPath" }
$b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($wasmPath))

$templatePath = Join-Path $PSScriptRoot "assets\verifier.html"
$html = [IO.File]::ReadAllText($templatePath, [Text.Encoding]::UTF8)
if (-not $html.Contains("__WASM_BASE64__")) { throw "template missing placeholder __WASM_BASE64__" }
$html = $html.Replace("__WASM_BASE64__", $b64)

# Kernel self-check vector (1-entry mini export doc, generated by tests/handlers.rs
# dump_browser_fixtures). Re-generate with:
#   $env:EVID_WASM_FIXTURE_DIR='dist\fixtures'; cargo test -p evid-verify-wasm --test handlers dump_browser_fixtures
$outDir = Join-Path $PSScriptRoot "dist"
$vectorPath = Join-Path $outDir "fixtures\self_check.json"
if (-not (Test-Path $vectorPath)) { throw "self-check vector missing: $vectorPath (see comment above to re-generate)" }
$vector = ([IO.File]::ReadAllText($vectorPath, [Text.Encoding]::UTF8)).Trim()
if (-not $html.Contains("__SELF_CHECK_VECTOR__")) { throw "template missing placeholder __SELF_CHECK_VECTOR__" }
$html = $html.Replace("__SELF_CHECK_VECTOR__", $vector)

New-Item -ItemType Directory -Force $outDir | Out-Null
$outPath = Join-Path $outDir "index.html"
# 2-arg WriteAllText: .NET default = UTF-8 without BOM
[IO.File]::WriteAllText($outPath, $html)
if (-not (Test-Path $outPath)) { throw "dist/index.html write failed" }
"OK: $outPath ($([math]::Round((Get-Item $outPath).Length/1KB)) KB)"
